import seaborn as sns
import matplotlib.pyplot as plt

tips = sns.load_dataset('tips')
print(tips.head())
sns.pairplot(tips)

plt.show()

tips = sns.load_dataset('tips')

sns.pairplot(tips, hue='sex')

plt.show()

tips = sns.load_dataset('tips')

sns.pairplot(
    tips,
    hue='smoker',
    diag_kind='kde'
)

plt.show()

tips = sns.load_dataset('tips')

sns.pairplot(
    tips,
    vars=['total_bill', 'tip']
)

plt.show()